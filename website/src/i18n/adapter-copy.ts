export function categoryLabel(category: string, lang: keyof typeof adapterCopy): string {
	const labels: Record<string, string> = adapterCopy[lang].categoryNames;
	if (Object.hasOwn(labels, category)) return labels[category];
	return category.replace(/[-_]+/g, " ").replace(/^./, (letter) => letter.toUpperCase());
}
